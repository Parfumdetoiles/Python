print("area y perimetro del rectangulo")
print("Ingrese la base del rectangulo")
baseRe = float(input())
print("Ingrese la altura del rectangulo")
alturaRe = float(input())
areaRe = baseRe * alturaRe
print("El area del rectangulo es: ", areaRe)
perimetroRe = 2 * (baseRe + alturaRe)
print("El perimetro del rectangulo es: ", perimetroRe)